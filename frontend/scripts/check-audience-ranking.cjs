const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
function load(relative) {
  const filename = path.resolve(__dirname, '../src/pipeline', relative);
  const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS } }).outputText;
  const module = { exports: {} };
  new Function('require', 'module', 'exports', compiled)(name => load(name + '.ts'), module, module.exports);
  return module.exports;
}
const { parseAudienceLimit, audienceScore, selectAudienceRanking } = load('audience-ranking.ts');
const { mergeRoomState, isFeedMessage } = load('messages.ts');
for (const limit of [1, 10, 13, 20, 50, 100]) assert.equal(parseAudienceLimit(String(limit)), limit);
for (const invalid of [null, undefined, '', '0', '101', '-1', '3.5', '1e2', '01', 'NaN', 'Infinity', '20a']) assert.equal(parseAudienceLimit(invalid), null);
assert.equal(parseAudienceLimit(' 15 '), 15);
const entry = score => ({ rank: 1, user_id: '42', user_name: '虚构用户', score });
assert.equal(audienceScore(entry(null)), '未提供', 'Omitted scores never become zero');
assert.equal(audienceScore(entry('0')), '0');
assert.equal(audienceScore(entry(0)), '0', 'Old backend explicit numeric zero remains compatible');
assert.equal(audienceScore(entry('9007199254740993')), '9,007,199,254,740,993');
assert.equal(audienceScore(entry(9007199254740993)), '未提供', 'An already rounded legacy number must not claim exact precision');
assert.equal(audienceScore({ ...entry('0'), score_description: '1.2万贡献', exactly_score: '12000' }), '1.2万贡献');
assert.equal(audienceScore({ ...entry(null), exactly_score: '未公开贡献' }), '未公开贡献');
assert.equal(audienceScore({ ...entry('500'), hidden: true, score_description: '私有描述' }), '未公开');
assert.equal(audienceScore(entry('garbage')), '未提供');
const online = (seq, time, ranks = [entry(null)]) => ({ type: 'online_count', method: 'legacy', live_id: '111', seq, received_at_ms: time, online_count: 0, audience_ranks: ranks });
const extended = (seq, time, ranks = [entry('500')]) => ({ type: 'audience_rank', live_id: '111', seq, received_at_ms: time, audience_ranks: ranks, audience_rank_source: 'room_rank', audience_ranks_total: ranks.length });
let states = mergeRoomState([], [online('1', 1000), extended('2', 2000)], '111');
assert.equal(states.length, 2); assert.equal(states[0].online_count, 0);
assert.equal(states[1].method, 'WebcastRoomRankMessage'); assert.equal(states[1].online_count, undefined);
assert.equal(selectAudienceRanking(states).seq, '2');
states = mergeRoomState(states, [online('3', 3000), extended('1', 1500), { ...extended('4', 4000), live_id: '222' }], '111');
assert.equal(states[0].seq, '2'); assert.equal(states[1].seq, '3');
assert.equal(selectAudienceRanking(states).seq, '2', 'Frequent top-three updates must not overwrite the expanded ranking');
states = mergeRoomState(states, [online('5', 63000)], '111');
assert.equal(selectAudienceRanking(states).seq, '5', 'An expanded source lagging over a minute yields to fresh online ranks');
states = mergeRoomState(states, [extended('9007199254740993', 64000, [])], '111');
assert.equal(selectAudienceRanking(states).audience_ranks.length, 0, 'An empty expanded snapshot must clear the prior users');
states = mergeRoomState(states, [extended('9007199254740992', 65000)], '111');
assert.equal(selectAudienceRanking(states).seq, '9007199254740993', '64-bit cursors reject an older replay');
assert.equal(isFeedMessage({ type: 'audience_rank' }), false);
assert.deepEqual(mergeRoomState(states, [], '222'), []);
assert.equal(selectAudienceRanking([]), undefined);
console.log('PASS: audience limits, exact/missing/zero/platform/hidden scores, independent room state, source freshness, empty snapshots and 64-bit replay cursors.');
