    await page.getByRole('button', { name: '配置 界面测试主播', exact: true }).click();
    await page.getByRole('button', { name: '配置 Cookie', exact: true }).click();
    await page.getByLabel('Cookie 请求头', { exact: true }).fill('ui-test-only');
    await page.getByRole('button', { name: '如何获取 Cookie？', exact: true }).click();
    await page.getByRole('link', { name: '抖音直播间', exact: true }).waitFor();
    await page.getByRole('button', { name: '关闭弹窗', exact: true }).click();
    await page.getByRole('button', { name: '查看 界面测试主播 的消息', exact: true }).click();
    await page.getByRole('searchbox', { name: '搜索消息', exact: true }).fill('未匹配');
