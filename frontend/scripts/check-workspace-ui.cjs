    await page.getByRole('button', { name: '配色说明', exact: true }).click();
    await page.getByRole('heading', { name: '配色说明', exact: true }).waitFor();
    await page.getByRole('button', { name: '关闭弹窗', exact: true }).click();
    await page.getByRole('button', { name: '信息汇总', exact: true }).click();
    await page.getByRole('searchbox', { name: '搜索全部行为记录' }).fill('测试');
    await page.getByRole('button', { name: '清空汇总搜索' }).click();
    await page.getByRole('button', { name: '查看消息详情 · 弹幕' }).click();
