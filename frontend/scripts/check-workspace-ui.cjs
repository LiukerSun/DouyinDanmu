    assert.equal(await page.getByRole('button', { name: '导出完整记录' }).count(), 0);
    await page.getByRole('button', { name: '关闭消息详情' }).click();
    debug = true;
    await page.getByRole('button', { name: '查看消息详情 · 弹幕' }).click();
